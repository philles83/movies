'use strict';

const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');

function validate(config) {
  const target = new URL(config.websiteURL);
  if (!/^https?:$/.test(target.protocol) || target.username || target.password) {
    throw new Error('websiteURL muss eine HTTP(S)-URL ohne Zugangsdaten sein.');
  }
  for (const host of config.navigation.allowedHosts) {
    if (typeof host !== 'string' || !host || host !== host.toLowerCase() ||
        new URL('https://' + host).hostname !== host || /[/:?#@*\s]/.test(host)) {
      throw new Error('allowedHosts erwartet exakte, kleingeschriebene Hostnamen.');
    }
  }
  for (const key of ['adSelectors', 'overlaySelectors', 'protectedSelectors']) {
    if (!Array.isArray(config.filters[key]) ||
        config.filters[key].some(s => typeof s !== 'string' || !s.trim())) {
      throw new Error('Ungültige Selektorliste: ' + key);
    }
  }
  for (const value of [config.filters.maxNodesPerPass, config.filters.batchDelayMs,
    config.remote.scrollStep, config.debug.maxEntries]) {
    if (!Number.isInteger(value) || value < 1 || value > 10000) {
      throw new Error('Arbeitslimits müssen ganze Zahlen zwischen 1 und 10000 sein.');
    }
  }
  for (const value of [config.navigation.blockPopups, config.navigation.guardLinks,
    config.filters.enabled, config.remote.enabled, config.debug.enabled, config.debug.showOverlay]) {
    if (typeof value !== 'boolean') throw new Error('Funktionsschalter müssen boolean sein.');
  }
}

function render(config) {
  validate(config);
  const runtime = require('../src/runtime.js');
  const css = fs.readFileSync(path.join(root, 'src/tv.css'), 'utf8');
  const bundle = '// GENERATED by npm run build. Edit config.js or src/, then rebuild.\n' +
    '(' + runtime.toString() + ')(' + JSON.stringify(config) + ',' + JSON.stringify(css) + ');\n';
  new vm.Script(bundle, { filename: 'main.js' });
  return bundle;
}

function build(check) {
  const config = require('../config.js');
  const bundle = render(config);
  const manifestPath = path.join(root, 'package.json');
  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
  const expected = { ...manifest, websiteURL: config.websiteURL };
  if (manifest.packageType !== 'mods' || manifest.main !== 'main.js' ||
      manifest.evaluateScriptOnDocumentStart !== false || !Array.isArray(manifest.keys)) {
    throw new Error('TizenBrew-Paketfelder sind inkonsistent.');
  }
  if (check) {
    if (manifest.websiteURL !== config.websiteURL ||
        fs.readFileSync(path.join(root, 'main.js'), 'utf8') !== bundle) {
      throw new Error('Veraltetes Paket oder Bundle. Bitte npm run build ausführen.');
    }
    console.log('Paket, Konfiguration und Injection-Bundle sind konsistent.');
  } else {
    fs.writeFileSync(manifestPath, JSON.stringify(expected, null, 2) + '\n');
    fs.writeFileSync(path.join(root, 'main.js'), bundle);
    console.log('main.js und websiteURL erstellt.');
  }
}

module.exports = { validate, render };
if (require.main === module) build(process.argv.includes('--check'));
